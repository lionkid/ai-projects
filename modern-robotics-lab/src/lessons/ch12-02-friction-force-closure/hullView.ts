/**
 * 3D wrench-space plot for the force-closure test: each friction-cone edge wrench is a point
 * (f_x, f_y, m/ρ) (x red, y green, z blue), drawn with a ray from the origin, together with the
 * (neutral) convex hull of the points and a marker at the origin (green when it is strictly inside).
 * Rendering is on demand (no continuous loop); colours are CSS variable names so theme switches work.
 */
import * as THREE from 'three';
import { Scene3D, themedStandardMaterial, setThemedColor } from '@/ui';
import { type V3, hullFaces, distinctPoints } from './grasp';

/** Half-lengths of the drawn axes: unit edge forces reach 1 in (f_x, f_y); |m/ρ| ≤ 1 by the choice of ρ. */
const AXIS: V3 = [1.3, 1.3, 0.92];

function lineMaterial(color: string, opacity = 1): THREE.LineBasicMaterial {
  const m = new THREE.LineBasicMaterial({ transparent: opacity < 1, opacity });
  setThemedColor(m, color);
  return m;
}

export class WrenchHullView {
  readonly scene: Scene3D;
  private readonly dyn = new THREE.Group();
  private readonly origin: THREE.Mesh;

  constructor(parent: HTMLElement, opts: { aspect?: number } = {}) {
    this.scene = new Scene3D(parent, {
      aspect: opts.aspect ?? 2.5, grid: false, axes: false, fov: 30,
      cameraPos: [2.35, -3.05, 1.55], target: [0, 0, -0.04], autoStart: false,
    });
    const axes: [number, string, string][] = [
      [0, '--axis-x', 'f_x'],
      [1, '--axis-y', 'f_y'],
      [2, '--axis-z', 'm/ρ'],
    ];
    for (const [k, color, label] of axes) {
      const d: V3 = [0, 0, 0];
      d[k] = AXIS[k];
      const a = this.scene.addArrow({ color, radius: 0.007, head: 0.08 });
      a.setFromTo([-d[0], -d[1], -d[2]], d);
      // x / y labels just past the arrow tips; the vertical label beside the tip so it never leaves the frame
      const pos: V3 = k === 2 ? [0.24, 0, d[2] - 0.08] : [d[0] * 1.13, d[1] * 1.13, 0];
      this.scene.addLabel(label, pos, color, 0.0026);
    }
    this.origin = this.scene.addSphere(0.065, '--danger');
    this.scene.scene.add(this.dyn);
  }

  /**
   * Redraw for a new set of points. `colors[i]` is the CSS variable of point i (its finger);
   * `inside` colours the origin marker.
   */
  update(points: V3[], colors: string[], inside: boolean): void {
    this.clearDyn();
    // the hull stays neutral so the finger-coloured points stand out; the origin marker carries the verdict
    const hullColor = '--fg-muted';
    setThemedColor(this.origin.material as THREE.MeshStandardMaterial, inside ? '--ok' : '--danger');
    this.origin.scale.setScalar(inside ? 1.1 : 1.3);

    // points and rays from the origin (the cone pos{𝓕ᵢ} is generated by these rays)
    points.forEach((p, i) => {
      const s = new THREE.Mesh(new THREE.SphereGeometry(0.048, 16, 12), themedStandardMaterial(colors[i] ?? '--fg', { roughness: 0.5 }));
      s.position.set(p[0], p[1], p[2]);
      this.dyn.add(s);
      const g = new THREE.BufferGeometry().setFromPoints([new THREE.Vector3(0, 0, 0), new THREE.Vector3(p[0], p[1], p[2])]);
      this.dyn.add(new THREE.Line(g, lineMaterial(colors[i] ?? '--fg-muted', 0.55)));
    });

    const faces = hullFaces(points);
    if (faces.length) {
      const pos: number[] = [];
      const edge: number[] = [];
      for (const f of faces) {
        const L = f.loop.map((i) => points[i]);
        for (let k = 1; k + 1 < L.length; k++) pos.push(...L[0], ...L[k], ...L[k + 1]);
        for (let k = 0; k < L.length; k++) edge.push(...L[k], ...L[(k + 1) % L.length]);
      }
      const geo = new THREE.BufferGeometry();
      geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
      geo.computeVertexNormals();
      const mesh = new THREE.Mesh(geo, themedStandardMaterial(hullColor, {
        transparent: true, opacity: 0.2, side: THREE.DoubleSide, depthWrite: false, roughness: 0.8,
      }));
      this.dyn.add(mesh);
      const eg = new THREE.BufferGeometry();
      eg.setAttribute('position', new THREE.Float32BufferAttribute(edge, 3));
      this.dyn.add(new THREE.LineSegments(eg, lineMaterial(hullColor, 0.85)));
    } else {
      // fewer than three non-collinear points: the hull is a segment (or a point)
      const keep = distinctPoints(points);
      if (keep.length >= 2) {
        const seg: number[] = [];
        for (let a = 0; a < keep.length; a++) for (let b = a + 1; b < keep.length; b++) seg.push(...points[keep[a]], ...points[keep[b]]);
        const eg = new THREE.BufferGeometry();
        eg.setAttribute('position', new THREE.Float32BufferAttribute(seg, 3));
        this.dyn.add(new THREE.LineSegments(eg, lineMaterial(hullColor, 0.85)));
      }
    }
    this.scene.requestRender();
  }

  private clearDyn(): void {
    for (const o of [...this.dyn.children]) {
      this.dyn.remove(o);
      const m = o as THREE.Mesh;
      m.geometry?.dispose();
      const mat = m.material as THREE.Material | THREE.Material[] | undefined;
      if (Array.isArray(mat)) mat.forEach((x) => x.dispose()); else mat?.dispose();
    }
  }

  destroy(): void {
    this.scene.destroy();
  }
}
