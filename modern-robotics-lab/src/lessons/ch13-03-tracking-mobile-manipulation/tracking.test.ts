import { describe, expect, it } from 'vitest';
import { adjointPose, between, compose, expTwist, logPose, pose } from './se2';
import { makeReference, PARK_GOAL, PARK_START, type RefKind } from './references';
import { lateralMode, rmsPositionError, saturateDiff, simulateTracking, wheelSpeeds, type TrackingConfig } from './tracking';

const near = (a: number, b: number, tol = 1e-9) => expect(Math.abs(a - b)).toBeLessThan(tol);

const BASE_CFG: TrackingConfig = {
  base: 'diff', ff: true, fb: true, errFrame: 'body',
  diff: { k1: 1.5, k2: 4, k3: 4 }, omni: { kp: 1.5, ki: 0 },
  bias: 0, push: null, start: pose(0, 0, -1),
};
const cfg = (o: Partial<TrackingConfig>): TrackingConfig => ({ ...BASE_CFG, ...o });
const last = <T>(a: T[]): T => a[a.length - 1];

describe('se2 helpers (built on @/mr)', () => {
  it('expTwist follows the circular arc of a constant twist', () => {
    const d = expTwist([1, 1, 0], Math.PI / 2); // radius 1, quarter turn to the left
    near(d.phi, Math.PI / 2); near(d.x, 1, 1e-12); near(d.y, 1, 1e-12);
    const s = expTwist([0, 0.3, -0.2], 2); // pure translation
    near(s.x, 0.6, 1e-12); near(s.y, -0.4, 1e-12);
  });

  it('logPose inverts expTwist', () => {
    for (const V of [[0.4, 1, -0.3], [-2.5, 0.2, 0.7], [1e-9, 0.5, 0.5], [3.0, -1, 0]] as [number, number, number][]) {
      const L = logPose(expTwist(V, 1));
      for (let i = 0; i < 3; i++) near(L[i], V[i], 1e-9);
    }
  });

  it('adjointPose has the planar closed form [[1,0,0],[y,c,−s],[−x,s,c]]', () => {
    const E = pose(0.7, 0.3, -0.4);
    const A = adjointPose(E);
    const c = Math.cos(0.7), s = Math.sin(0.7);
    const ref = [[1, 0, 0], [E.y, c, -s], [-E.x, s, c]];
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) near(A[i][j], ref[i][j], 1e-12);
  });

  it('between undoes compose', () => {
    const a = pose(0.4, 1, 2), b = pose(-1.1, -0.5, 0.3);
    const back = compose(a, between(a, b));
    near(back.x, b.x, 1e-12); near(back.y, b.y, 1e-12); near(Math.cos(back.phi - b.phi), 1, 1e-12);
  });
});

describe('reference trajectories', () => {
  const feasible: RefKind[] = ['circle', 'scurve', 'parking', 'still'];
  it.each(feasible)('%s is generated by the unicycle model: zero lateral velocity, consistent v_d', (kind) => {
    const ref = makeReference(kind);
    const dt = 1e-5;
    for (let i = 1; i < 300; i++) {
      const t = (ref.T * i) / 300;
      const a = ref.sample(t - dt).q, b = ref.sample(t + dt).q, q = ref.sample(t).q;
      const vx = (b.x - a.x) / (2 * dt), vy = (b.y - a.y) / (2 * dt);
      expect(Math.abs(-Math.sin(q.phi) * vx + Math.cos(q.phi) * vy)).toBeLessThan(1e-4);
      expect(Math.abs(Math.cos(q.phi) * vx + Math.sin(q.phi) * vy - ref.sample(t).V[1])).toBeLessThan(1e-3);
      expect(ref.sample(t).V[2]).toBe(0);
    }
    expect(ref.maxLateral).toBe(0);
  });

  it('circle has radius 1 m about the origin', () => {
    const ref = makeReference('circle');
    for (const p of ref.path) near(Math.hypot(p.x, p.y), 1, 1e-9);
    near(ref.sample(1).V[1], 0.5, 1e-12); near(ref.sample(1).V[0], 0.5, 1e-12);
  });

  it('parking shifts the robot sideways by 0.8 m with one gear change', () => {
    const ref = makeReference('parking');
    const e = ref.sample(ref.T).q;
    near(e.x, PARK_GOAL.x, 1e-9); near(e.y, PARK_GOAL.y, 1e-9); near(e.phi, 0, 1e-9);
    expect(ref.cusps.length).toBe(1);
    expect(ref.sample(7).V[1]).toBeLessThan(0); // the second move is driven in reverse
  });

  it('straight-line interpolation of q asks for sideways motion (infeasible for a diff drive)', () => {
    const ref = makeReference('sideways');
    near(ref.start.x, PARK_START.x); near(ref.sample(ref.T).q.y, PARK_GOAL.y, 1e-12);
    expect(ref.maxLateral).toBeCloseTo((1.875 * 0.8) / 6, 3);
    expect(Math.abs(ref.sample(3).V[1])).toBeLessThan(1e-12); // no forward component at all
  });

  it('every reference fits the 4.8 m × 3 m canvas', () => {
    for (const k of ['circle', 'scurve', 'parking', 'sideways', 'still'] as RefKind[]) {
      for (const p of makeReference(k).path) { expect(Math.abs(p.x)).toBeLessThan(2.3); expect(Math.abs(p.y)).toBeLessThan(1.4); }
    }
  });
});

describe('differential-drive tracking', () => {
  const circle = makeReference('circle');
  const offset = pose(0.3, 0, -1.3); // 0.3 m outside the circle, heading 17° off

  it('feedforward alone replays the path: exact start → no error, offset start → the error never decays', () => {
    const exact = simulateTracking(circle, cfg({ fb: false }));
    expect(rmsPositionError(exact)).toBeLessThan(1e-9);
    const shifted = simulateTracking(circle, cfg({ fb: false, start: pose(0, 0, -1.3) }));
    // The robot drives an identical circle shifted by 0.3 m: the error stays at 0.3 m.
    const e = last(shifted.err);
    near(Math.hypot(e[1], e[2]), 0.3, 1e-6);
    const biased = simulateTracking(circle, cfg({ fb: false, bias: 0.1 }));
    const eb = last(biased.err);
    expect(Math.hypot(eb[1], eb[2])).toBeGreaterThan(0.5); // a small wheel bias makes it drift away
  });

  it('feedforward + feedback removes an initial offset', () => {
    const tr = simulateTracking(circle, cfg({ start: offset }));
    expect(rmsPositionError(tr, 12)).toBeLessThan(0.01);
    expect(Math.abs(last(tr.err)[0])).toBeLessThan(0.01);
  });

  it('feedback alone lags behind a moving reference', () => {
    const tr = simulateTracking(circle, cfg({ ff: false, start: offset }));
    expect(rmsPositionError(tr, 10)).toBeGreaterThan(0.15);
  });

  it('the same law fed with world-frame errors diverges once the heading turns around', () => {
    const tr = simulateTracking(circle, cfg({ start: offset, errFrame: 'world' }));
    const good = simulateTracking(circle, cfg({ start: offset }));
    expect(rmsPositionError(tr, 8)).toBeGreaterThan(0.5);
    expect(rmsPositionError(good, 8)).toBeLessThan(0.05);
  });

  it('with v_d = 0 the lateral error is never corrected (only x_e is)', () => {
    const still = makeReference('still');
    const tr = simulateTracking(still, cfg({ start: pose(0, -0.3, 0.25) }));
    const e = last(tr.err);
    expect(Math.abs(e[1])).toBeLessThan(1e-3);
    near(e[2], -0.25, 1e-9);
  });

  it('a sideways reference leaves a differential drive standing still', () => {
    const ref = makeReference('sideways');
    const tr = simulateTracking(ref, cfg({ start: { ...PARK_START } }));
    near(last(tr.q).x, PARK_START.x, 1e-9); near(last(tr.q).y, PARK_START.y, 1e-9);
    near(last(tr.err)[2], 0.8, 1e-9);
  });

  it('the parking reference (with reversing) is tracked from an offset start', () => {
    const ref = makeReference('parking');
    const tr = simulateTracking(ref, cfg({ start: pose(0.2, -0.85, -0.55) }));
    // v_d → 0 at the gear change and at the end, so some error remains; it must still shrink a lot.
    expect(Math.hypot(last(tr.err)[1], last(tr.err)[2])).toBeLessThan(0.08);
  });

  it('a large k2 (small ζ = k3 / 2√k2) makes the lateral error overshoot', () => {
    const lowZ = simulateTracking(circle, cfg({ start: pose(0, 0, -1.3), diff: { k1: 1.5, k2: 36, k3: 2 } }));
    const crit = simulateTracking(circle, cfg({ start: pose(0, 0, -1.3), diff: { k1: 1.5, k2: 4, k3: 4 } }));
    const minY = (tr: typeof lowZ) => Math.min(...tr.err.map((e) => e[2]));
    expect(minY(lowZ)).toBeLessThan(-0.06);
    expect(minY(crit)).toBeGreaterThan(-0.03);
    near(lateralMode(0.5, 36, 2).zeta, 2 / 12); near(lateralMode(0.5, 36, 2).wn, 3);
  });

  it('wheel saturation scales v and ω together (curvature preserved)', () => {
    const s = saturateDiff(2, 3);
    expect(s.sat).toBe(true);
    near(s.w / s.v, 1.5, 1e-12);
    const [uL, uR] = wheelSpeeds(s.v, s.w);
    near(Math.max(Math.abs(uL), Math.abs(uR)), 15, 1e-9);
    expect(saturateDiff(0.5, 0.5).sat).toBe(false);
  });
});

describe('omnidirectional tracking (twist feedforward + PI)', () => {
  const circle = makeReference('circle');
  const omni = (o: Partial<TrackingConfig>) => cfg({ base: 'omni', ...o });

  it('P feedback leaves a steady heading offset ≈ −bias / Kp; adding Ki removes it', () => {
    const p = simulateTracking(circle, omni({ bias: 0.3, omni: { kp: 1.5, ki: 0 } }));
    near(last(p.err)[0], -0.2, 5e-3);
    const pi = simulateTracking(circle, omni({ bias: 0.3, omni: { kp: 1.5, ki: 1 } }));
    expect(Math.abs(last(pi.err)[0])).toBeLessThan(5e-3);
    expect(rmsPositionError(pi, 12)).toBeLessThan(5e-3);
  });

  it('follows the sideways reference that a differential drive cannot', () => {
    const tr = simulateTracking(makeReference('sideways'), omni({ start: { ...PARK_START } }));
    // Only the sub-millimetre lag of holding V_d constant over each 10 ms period remains.
    expect(rmsPositionError(tr)).toBeLessThan(1e-3);
    near(last(tr.q).y, PARK_GOAL.y, 1e-3);
  });

  it('removes an initial offset in all three directions at once', () => {
    const tr = simulateTracking(circle, omni({ start: pose(0.4, 0.2, -1.3) }));
    expect(rmsPositionError(tr, 8)).toBeLessThan(1e-3);
  });
});
